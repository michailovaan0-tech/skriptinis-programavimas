x1 = linspace(-2, 2, 20);
y1 = linspace(-2, 2, 20);
z1 = linspace(-1, 1, 20);
[X1, Y1, Z1] = meshgrid(x1, y1, z1);
R2 = X1.^2 + Y1.^2 + Z1.^2;
f1 = sin(R2 / 20) .* exp(-R2);
figure(1);
h = slice(X1, Y1, Z1, f1, 0, 0, 0);
shading interp;
colormap jet;
view(90, 30);
title('Trimatis tūrio grafikas: f(x,y,z)');
xlabel('X ašis');
ylabel('Y ašis');
zlabel('Z ašis');

x2 = linspace(-2, 2, 60);
y2 = linspace(-2, 2, 60);
[X2, Y2] = meshgrid(x2, y2);
abs_xy = abs(X2 + Y2);
f2 = sin(abs_xy / 20) .* exp(-abs_xy);
figure(2);
surf(X2, Y2, f2);
shading interp;
colormap parula;
view(60, 30);
title('Dvimatis grafikas: f(x,y)');
xlabel('X ašis');
ylabel('Y ašis');
zlabel('Z ašis');

x3 = linspace(-2, 2, 40);
y3 = linspace(-2, 2, 40);
[X3, Y3] = meshgrid(x3, y3);
Z3 = 1 - (X3.^2 + Y3.^2);
figure(3); 
surf(X3, Y3, Z3);
shading interp;
colormap hot;
title('Paviršiaus grafikas su ''hot'' atspalviu');
xlabel('X ašis'); 
ylabel('Y ašis'); 
zlabel('Z ašis');